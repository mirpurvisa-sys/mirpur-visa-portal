test('search escapes wildcard and SQL text, and normalizes spaced identifiers',()=>{
  assert.deepEqual(Array.from(search.studentSearch('', 'ielts').values),[]);
  const escaped=search.studentSearch("O'Brien %_",'ielts');
  assert.ok(!escaped.condition.includes("O'Brien"));
  assert.ok(escaped.values.includes('%\\%\\_%'));
  assert.ok(search.studentSearch('12345 6789012 3','ielts').values.includes('%1234567890123%'));
});

test('student fees reconcile once, track CRUD, and are searchable in income and topbar', {skip:process.env.RUN_DATABASE_FINANCE_TESTS!=='1'},async t=>{
  const db=await connectPortalDatabase(),schema='student_finance_test_'+Date.now();
  let pending=Promise.resolve();
  const query=(sql,values)=>{const result=pending.then(()=>db.query(sql.replace(/\bpublic\./g,schema+'.'),values));pending=result.catch(()=>{});return result;};
  const migration=readFileSync(new URL('./student-fee-income.sql',import.meta.url),'utf8');
  const total=async()=>Number((await query(`WITH ${finance.RECEIVED_INCOME_CTE} SELECT sum(amount) AS total FROM received_income`)).rows[0].total||0);
  try {
    await db.query('BEGIN');await db.query("SET LOCAL statement_timeout='10s'");
    await db.query(`CREATE SCHEMA ${schema}`);
    for(const table of ['ielts','life_skills','incomes','expenses','case_installments','appointments','client_cases','clients','employees','users']){
      await db.query(`CREATE TABLE ${schema}.${table} AS SELECT * FROM public.${table} WHERE false`);
    }
    await query('ALTER TABLE public.incomes ALTER COLUMN id SET NOT NULL');
    await query('ALTER TABLE public.incomes ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY');
    await db.query(`SET LOCAL search_path TO ${schema},pg_catalog`);
    await query(`INSERT INTO public.ielts(id,name,cnic,phone,email,fee,joining_date,category) VALUES(17,'Synthetic Student','12345-6789012-3','0312-3456789','student@example.invalid',20000,'2026-10-01','General')`);
    await query(`INSERT INTO public.life_skills(id,name,cnic,phone,email,fee,admission_date,level) VALUES(17,'Synthetic Skills','12345-0000000-3','0333-1234567','skills@example.invalid',25000,'2026-10-02','Intermediate')`);
    await query(`INSERT INTO public.incomes("Title","IncomesType","Amount","Date",foreign_id) VALUES('Legacy student receipt','Course IELTS Fee',20000,'2026-09-30','1712345-6789012-3'),('Independent income','Other',1000,'2026-10-03',NULL)`);
    const before=await total();assert.equal(before,21000);
    await query(migration);
    await t.test('backfill preserves the imported receipt and adds only the missing fee',async()=>{
      assert.equal(await total(),46000);
      assert.equal((await query('SELECT count(*)::int AS n FROM public.incomes')).rows[0].n,3);
      assert.equal((await query("SELECT id FROM public.incomes WHERE student_course='ielts' AND student_id=17")).rows[0].id,1);
      await query(migration);assert.equal(await total(),46000);
      assert.equal(String((await query('SELECT "Date"::text AS date FROM public.incomes WHERE id=1')).rows[0].date),"2026-09-30");
    });
    await t.test('student and income searches find normalized identifiers, courses and older entries',async()=>{
      for(const q of ['Synthetic Student','1234567890123','12345 6789012 3','03123456789','student@example.invalid','17','IELTS #17']){
        const filter=search.studentSearch(q,'ielts');
        assert.equal((await query(`SELECT id FROM public.ielts WHERE ${filter.condition}`,filter.values)).rows.length,1,q);
      }
      const items=await transactions.getIncomeTransactions({query},'Synthetic');assert.equal(items.length,2);
      assert.ok(items.every(row=>row.source_type==='student_fee'));
      assert.ok(items.some(row=>row.href==='/admin/ielts?view=17'));
      assert.ok(items.some(row=>row.href==='/admin/life-skills?view=17'));
      await query(`INSERT INTO public.incomes("Title","IncomesType","Amount","Date") SELECT 'Unrelated '||n,'Other',1,'2026-10-28' FROM generate_series(1,100) n`);
      assert.equal((await transactions.getIncomeTransactions({query},'Independent')).length,1);
    });
    await t.test('accountant topbar finds students and money, while other roles cannot read financial results',async()=>{
      const config=evaluate('../lib/adminConfig.ts');
      const permissions=evaluate('../lib/permissions.ts',{'./adminConfig':config});
      const visibility=evaluate('../lib/caseAccess.ts',{'./permissions':permissions});
      const clients=evaluate('../lib/clientSearch.ts');
      let current={id:7,userType:'Accountant',roleSlugs:['accountant'],permissionSlugs:[]};
      const api=evaluate('../app/api/topbar/route.ts',{
        'next/server':{NextResponse:{json:body=>({body})}},
        '@/lib/auth':{requireUser:async()=>current},'@/lib/db':{getDb:()=>({query})},
        '@/lib/permissions':permissions,'@/lib/caseAccess':visibility,'@/lib/clientSearch':clients,
        '@/lib/recordSearch':search,'@/lib/incomeTransactions':transactions,'@/lib/caseNotifications':{},
      });
      let results=(await api.GET({url:'https://example.invalid/api/topbar?scope=search&q=Synthetic'})).body.searchItems;
      assert.ok(results.some(item=>item.group==='IELTS Students'));
      assert.ok(results.some(item=>item.group==='Life Skills Students'));
      assert.ok(results.some(item=>item.group==='Income'));
      await query(`INSERT INTO public.expenses(id,voucher_no,"Title","ExpenseType","Amount") VALUES(1,'EXP-987','Synthetic expense','Other',100)`);
      results=(await api.GET({url:'https://example.invalid/api/topbar?scope=search&q=EXP-987'})).body.searchItems;
      assert.ok(results.some(item=>item.href==='/admin/expenses?view=1'));
      current={...current,userType:'Teacher',roleSlugs:['teacher']};
      results=(await api.GET({url:'https://example.invalid/api/topbar?scope=search&q=Synthetic'})).body.searchItems;
      assert.ok(results.some(item=>item.group==='IELTS Students'));
      assert.ok(!results.some(item=>['Income','Expenses'].includes(item.group)));
      current={...current,userType:'Case Officer',roleSlugs:['case_officer']};
      results=(await api.GET({url:'https://example.invalid/api/topbar?scope=search&q=Synthetic'})).body.searchItems;
      assert.ok(!results.some(item=>['Income','Expenses','IELTS Students','Life Skills Students'].includes(item.group)));
    });
    await t.test('fee updates and CNIC corrections keep one receipt; zero and delete remove it',async()=>{
      await query("UPDATE public.ielts SET fee=22000,cnic='12345-9999999-3' WHERE id=17");
      assert.equal((await query("SELECT count(*)::int AS n,sum(\"Amount\") AS amount FROM public.incomes WHERE student_course='ielts'")).rows[0].n,1);
      assert.equal(Number((await query("SELECT \"Amount\" FROM public.incomes WHERE student_course='ielts'")).rows[0].Amount),22000);
      await query('UPDATE public.ielts SET fee=0 WHERE id=17');
      assert.equal((await query("SELECT * FROM public.incomes WHERE student_course='ielts'")).rows.length,0);
      await query('UPDATE public.ielts SET fee=23000 WHERE id=17');
      await query('DELETE FROM public.ielts WHERE id=17');
      assert.equal((await query("SELECT * FROM public.incomes WHERE student_course='ielts'")).rows.length,0);
      assert.equal((await query("SELECT * FROM public.incomes WHERE student_course='life-skills'")).rows.length,1);
      await query('DELETE FROM public.life_skills WHERE id=17');
      assert.equal((await query('SELECT * FROM public.incomes WHERE student_course IS NOT NULL')).rows.length,0);
    });
    await t.test('negative fees roll back the student write',async()=>{
      await query('SAVEPOINT invalid_fee');
      await assert.rejects(query("INSERT INTO public.ielts(id,name,fee) VALUES(90,'Negative',-1)"),/negative/);
      await query('ROLLBACK TO SAVEPOINT invalid_fee');
      assert.equal((await query('SELECT * FROM public.ielts WHERE id=90')).rows.length,0);
    });
    await t.test('income date totals use the recorded admission date',async()=>{
      await query("INSERT INTO public.ielts(id,name,fee,joining_date) VALUES(91,'Date test',500,'2026-09-10')");
      const r=await query(`WITH ${finance.RECEIVED_INCOME_CTE} SELECT sum(amount) AS amount FROM received_income WHERE received_on='2026-09-10'`);
      assert.equal(Number(r.rows[0].amount),500);
    });
    await t.test('both student lists paginate ten newest registrations first, preserving search',async()=>{
      for(const [course,table] of [['ielts','ielts'],['life-skills','life_skills']]) {
        await query(`DELETE FROM public.${table}`);
        await query(`INSERT INTO public.${table}(id,name,fee,created_at) SELECT n,'Page Fixture '||n,0,'2026-10-01'::timestamp + (n/2)*interval '1 day' FROM generate_series(1,23) n`);
        const first=await studentList.getStudentPage({query},course,'Page Fixture','1');
        assert.equal(first.total,23);assert.equal(first.totalPages,3);assert.equal(first.students.length,10);
        assert.deepEqual(Array.from(first.students,row=>Number(row.id)),[23,22,21,20,19,18,17,16,15,14]);
        const second=await studentList.getStudentPage({query},course,'Page Fixture','2');
        assert.equal(second.offset,10);assert.equal(second.students.length,10);
        assert.deepEqual(Array.from(second.students,row=>Number(row.id)),[13,12,11,10,9,8,7,6,5,4]);
        const last=await studentList.getStudentPage({query},course,'Page Fixture','999');
        assert.equal(last.page,3);assert.equal(last.students.length,3);
        for(const invalid of ['0','-1','NaN','2.5']) assert.equal((await studentList.getStudentPage({query},course,'Page Fixture',invalid)).page,1);
        const filtered=await studentList.getStudentPage({query},course,'Page Fixture 23','2');
        assert.equal(filtered.total,1);assert.equal(filtered.page,1);assert.equal(Number(filtered.students[0].id),23);
        const empty=await studentList.getStudentPage({query},course,'missing','3');
        assert.equal(empty.total,0);assert.equal(empty.page,1);assert.equal(empty.students.length,0);
        assert.equal(studentList.studentListHref(course,'a & b',2),`/admin/${course}?q=a+%26+b&page=2`);
      }
    });
  }finally{await db.query('ROLLBACK');await db.end();}
});

